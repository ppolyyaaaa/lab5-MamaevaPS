# выводим заголовок таблицы
print("x        y")

# выводим разделительную линию из 10 символов '-'
print('-' * 10)

# цикл перебирает значения x от -5 до 5 включительно
for x in range(-5, 6):
    y = x ** 2 - 2 * x + 1 # выводим x и соответствующее значение y

    # выводим x и соответствующее значение y
    print(f"{x}       {y}")