#include <iostream>  
#include <windows.h> 

using namespace std;

int main() {
    // Устанавливаем кодировку UTF-8 для ввода и вывода в консоли
    SetConsoleCP(CP_UTF8);
    SetConsoleOutputCP(CP_UTF8);

    int N, M; // N — высота фигур, M — ширина прямоугольника

    cout << "Введите высоту N: ";
    if (!(cin >> N) || N <= 0) { // Проверяем, что введено положительное целое число
        cout << "Ошибка: N должно быть положительным числом.\n";
        return 1; 
    }

    cout << "Введите ширину M: ";
    if (!(cin >> M) || M <= 0) { // Проверяем правильность введённого значения
        cout << "Ошибка: M должно быть положительным числом.\n";
        return 1;
    }

    // 1. Выводим прямоугольник размером N x M
    cout << "\n1. Прямоугольник:\n";

    for (int i = 0; i < N; i++) {       // Цикл перебирает строки
        for (int j = 0; j < M; j++) {   // Цикл выводит M звёздочек в строке
            cout << "* ";
        }
        cout << '\n'; // Переходим на следующую строку
    }

    // 2. Выводим прямоугольный треугольник высотой N
    cout << "\n2. Треугольник:\n";

    for (int i = 1; i <= N; i++) {      // Количество строк от 1 до N
        for (int j = 1; j <= i; j++) {  // В каждой строке выводим i звёздочек
            cout << "* ";
        }
        cout << '\n'; // Переходим на следующую строку
    }

    // 3. Выводим ёлочку высотой N
    cout << "\n3. Ёлочка:\n";

    for (int i = 1; i <= N; i++) {      // Формируем строки ёлочки
        for (int j = 0; j < N - i; j++) {
            cout << ' '; // Добавляем пробелы слева для центрирования
        }

        for (int j = 1; j <= 2 * i - 1; j++) {
            cout << '*'; // Выводим нечётное число звёздочек
        }

        cout << '\n'; // Переходим на следующую строку
    }

    // 4. Выводим ромб высотой 2N - 1 строк
    cout << "\n4. Ромб:\n";

    // Верхняя половина ромба вместе с центральной строкой
    for (int i = 1; i <= N; i++) {
        for (int j = 0; j < N - i; j++) {
            cout << ' '; // Добавляем пробелы слева
        }

        for (int j = 1; j <= 2 * i - 1; j++) {
            cout << '*'; // Выводим звёздочки
        }

        cout << '\n';
    }

    // Нижняя половина ромба
    for (int i = N - 1; i >= 1; i--) {
        for (int j = 0; j < N - i; j++) {
            cout << ' '; // Постепенно увеличиваем отступ слева
        }

        for (int j = 1; j <= 2 * i - 1; j++) {
            cout << '*'; // Постепенно уменьшаем количество звёздочек
        }

        cout << '\n';
    }

    return 0; 
}



